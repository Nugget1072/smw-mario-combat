"""Export Mario Combat's hero (DefineSprite 440 and everything under it) to C data for the SMW port.

Usage: python -I mc_export.py <MarioCombat.swf> <ffdec_images_dir> <out_c_file> <out_preview_dir>

Every shape is rasterized at "native art" resolution: k = output pixels per stage pixel, chosen from the
shape's on-stage scale so that 1 art pixel = 1 output pixel = 1 SNES pixel (stage px / 3). Timelines are
exported as per-frame op lists that the C timeline player (mc_core.c) replays with AVM1 semantics.
"""
import json, math, os, sys
import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from swflib import Swf  # noqa: E402
from swfraster import raster_shape  # noqa: E402

ROOT_SPRITE = 440
STAGE_PER_ART = 3.0  # stage pixels per art pixel (see notes/DATA_NOTES.md)


def mat_mul(p, c):
    """Compose parent p with child c (both [a,b,c,d,tx,ty], tx/ty in px)."""
    a = p[0] * c[0] + p[2] * c[1]
    b = p[1] * c[0] + p[3] * c[1]
    cc = p[0] * c[2] + p[2] * c[3]
    d = p[1] * c[2] + p[3] * c[3]
    tx = p[0] * c[4] + p[2] * c[5] + p[4]
    ty = p[1] * c[4] + p[3] * c[5] + p[5]
    return [a, b, cc, d, tx, ty]


def px_matrix(m):
    return [m[0], m[1], m[2], m[3], m[4] / 20, m[5] / 20] if m else [1, 0, 0, 1, 0, 0]


def main():
    swf_path, img_dir, out_c, prev_dir = sys.argv[1:5]
    swf = Swf(swf_path)
    os.makedirs(prev_dir, exist_ok=True)

    # ---- collect the character tree and usage scales ----
    usage = {}  # shape id -> list of |scale|
    sprites, shapes = [], []
    seen = set()

    def visit(cid, mat):
        if cid in swf.sprites:
            if cid not in seen:
                seen.add(cid); sprites.append(cid)
            cur = {}
            for f in range(1, swf.sprites[cid]["frames"] + 1):
                for op in swf.sprites[cid]["ops"].get(f, []):
                    if op["op"] == "remove":
                        cur.pop(op["depth"], None)
                    elif op["op"] == "place":
                        prev = cur.get(op["depth"])
                        ch = op.get("id", prev[0] if prev else None)
                        # PlaceObject2 with Move set keeps the old matrix unless a new one is given,
                        # even when it swaps the character at that depth.
                        m = px_matrix(op["matrix"]) if "matrix" in op else (prev[1] if prev and op["move"] else [1, 0, 0, 1, 0, 0])
                        cur[op["depth"]] = (ch, m)
                        key = (cid, f, op["depth"])
                        if ch is not None and (ch, tuple(np.round(mat_mul(mat, m), 3))) not in visited:
                            visited.add((ch, tuple(np.round(mat_mul(mat, m), 3))))
                            visit(ch, mat_mul(mat, m))
        elif cid in swf.shapes:
            if cid not in seen:
                seen.add(cid); shapes.append(cid)
            usage.setdefault(cid, []).append(math.sqrt(abs(mat[0] * mat[3] - mat[1] * mat[2])))

    visited = set()
    visit(ROOT_SPRITE, [1, 0, 0, 1, 0, 0])

    # ---- bitmaps (FFDec export, straight alpha) ----
    bitmaps = {}
    for f in os.listdir(img_dir):
        stem = f.split(".")[0]
        if stem.isdigit():
            im = Image.open(os.path.join(img_dir, f)).convert("RGBA")
            bitmaps[int(stem)] = np.asarray(im, np.float32) / 255

    # ---- rasterize shapes ----
    images, shape_img = [], {}
    report = []
    for sid in sorted(shapes):
        sh = swf.shapes[sid]
        sc = sorted(usage[sid])[len(usage[sid]) // 2]
        k = sc / STAGE_PER_ART
        for nice in (1.0, 1 / 3):
            if abs(k / nice - 1) < 0.06:
                k = nice
        x0, x1, y0, y1 = [v / 20 for v in sh["bounds"]]
        w = max(1, int(math.ceil((x1 - x0) * k - 1e-6)))
        h = max(1, int(math.ceil((y1 - y0) * k - 1e-6)))
        xf = (k / 20, 0, 0, k / 20, -x0 * k, -y0 * k)
        rgba = raster_shape(sh, bitmaps, xf, w, h)
        a8 = (rgba * 255 + 0.5).astype(np.uint8)
        Image.fromarray(a8, "RGBA").save(os.path.join(prev_dir, f"shape_{sid}.png"))
        shape_img[sid] = len(images)
        images.append({"id": sid, "w": w, "h": h, "k": k, "ox": x0, "oy": y0, "rgba": a8})
        report.append({"shape": sid, "w": w, "h": h, "k": k, "scales": sorted(set(round(s, 3) for s in usage[sid])),
                       "lines": any(e[2] for g in sh["groups"] for e in g["edges"])})

    # ---- names / sprites ----
    names = []

    def name_idx(n):
        if n is None:
            return -1
        if n not in names:
            names.append(n)
        return names.index(n)

    sprite_idx = {sid: i for i, sid in enumerate(sprites)}
    lines = ['// Generated by tools/scripts/mc_export.py from Mario Combat (DefineSprite 440 tree). Do not edit.',
             '#include "mc_data.h"', '']
    for im in images:
        argb = im["rgba"].astype(np.uint32)
        packed = (argb[..., 3] << 24) | (argb[..., 0] << 16) | (argb[..., 1] << 8) | argb[..., 2]
        vals = ",".join(f"0x{v:08x}" for v in packed.flatten())
        lines.append(f"static const uint32 kImg{im['id']}[] = {{{vals}}};")
    lines.append("const McImage kMcImages[] = {")
    for im in images:
        lines.append(f"  {{{im['w']}, {im['h']}, {im['k']:.6f}f, {im['ox']:.4f}f, {im['oy']:.4f}f, kImg{im['id']}}},  // shape {im['id']}")
    lines.append("};")
    lines.append(f"const int kMcNumImages = {len(images)};")

    sounds_used = set()
    all_ops, frame_starts, sprite_rows = [], [], []
    for sid in sprites:
        t = swf.sprites[sid]
        start = len(frame_starts)
        for f in range(1, t["frames"] + 1):
            frame_starts.append(len(all_ops))
            for op in t["ops"].get(f, []):
                if op["op"] == "place":
                    fl = (1 if op["move"] else 0) | (2 if "id" in op else 0) | (4 if "matrix" in op else 0) | \
                         (8 if "cxform" in op else 0) | (16 if "ratio" in op else 0) | (32 if "name" in op else 0)
                    m = px_matrix(op.get("matrix"))
                    cx = op.get("cxform", {"mul": [256] * 4, "add": [0] * 4})
                    all_ops.append(("MC_OP_PLACE", fl, op["depth"], op.get("id", 0), name_idx(op.get("name")),
                                    op.get("ratio", 0), m, cx["mul"] + cx["add"]))
                elif op["op"] == "remove":
                    all_ops.append(("MC_OP_REMOVE", 0, op["depth"], 0, -1, 0, [1, 0, 0, 1, 0, 0], [256] * 4 + [0] * 4))
                elif op["op"] == "sound":
                    sounds_used.add(op["id"])
                    all_ops.append(("MC_OP_SOUND", 0, 0, op["id"], -1, 0, [1, 0, 0, 1, 0, 0], [256] * 4 + [0] * 4))
        frame_starts.append(len(all_ops))  # sentinel for the last frame
        sprite_rows.append((sid, t["frames"], start))
    lines.append("const McOp kMcOps[] = {")
    for kind, fl, dep, ch, nm, ratio, m, cx in all_ops:
        lines.append(f"  {{{kind}, {fl}, {dep}, {ch}, {nm}, {ratio}, {{{m[0]:.6f}f, {m[1]:.6f}f, {m[2]:.6f}f, {m[3]:.6f}f, "
                     f"{m[4]:.4f}f, {m[5]:.4f}f}}, {{{','.join(str(v) for v in cx)}}}}},")
    lines.append("};")
    lines.append("const uint16 kMcFrameStart[] = {" + ",".join(str(v) for v in frame_starts) + "};")
    lines.append("const McSpriteDef kMcSprites[] = {")
    for sid, nf, start in sprite_rows:
        lines.append(f"  {{{sid}, {nf}, {start}}},")
    lines.append("};")
    lines.append(f"const int kMcNumSprites = {len(sprites)};")
    labels = [(sid, f, n) for sid in sprites for n, f in swf.sprites[sid]["labels"].items()]
    lines.append("const McLabel kMcLabels[] = {")
    for sid, f, n in labels:
        lines.append(f'  {{{sid}, {f}, "{n}"}},')
    lines.append("};")
    lines.append(f"const int kMcNumLabels = {len(labels)};")
    lines.append("const char *const kMcNames[] = {" + ",".join(f'"{n}"' for n in names) + "};")
    lines.append(f"const int kMcNumNames = {len(names)};")
    max_id = max(list(shapes) + list(sprites))
    lines.append(f"const int kMcMaxCharId = {max_id};")
    chars = ["{0,0}"] * (max_id + 1)
    for sid, i in shape_img.items():
        chars[sid] = f"{{1,{i}}}"
    for sid, i in sprite_idx.items():
        chars[sid] = f"{{2,{i}}}"
    lines.append("const McCharDef kMcChars[] = {" + ",".join(chars) + "};")
    # Bounds of every exported character's shapes (used for hitTest-style bounding boxes)
    lines.append("const McShapeBounds kMcShapeBounds[] = {")
    for im in images:
        b = [v / 20 for v in swf.shapes[im["id"]]["bounds"]]
        lines.append(f"  {{{im['id']}, {b[0]:.4f}f, {b[1]:.4f}f, {b[2]:.4f}f, {b[3]:.4f}f}},")
    lines.append("};")
    open(out_c, "w").write("\n".join(lines) + "\n")
    json.dump({"images": report, "sprites": sprites, "sounds": sorted(sounds_used), "names": names},
              open(os.path.join(prev_dir, "export_report.json"), "w"), indent=1)
    print(f"{len(images)} images, {len(sprites)} sprites, {len(all_ops)} ops, sounds {sorted(sounds_used)}")


if __name__ == "__main__":
    main()
