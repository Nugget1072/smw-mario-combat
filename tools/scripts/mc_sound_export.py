"""Embed Mario Combat's hero sounds (FFDec WAV export) as 22050 Hz mono int16 C arrays.

Usage: python -I mc_sound_export.py <ffdec_sounds_dir> <report.json>[,<report2.json>...] <out_c_file>
The sound ids are the ones the exported timelines start: export_report.json from mc_export.py (the hero) and
koopa_report.json / bowser_report.json from mc_enemy_export.py (the enemy Koopa, Bowser with his flame and shockwave).
"""
import json, os, sys, wave
import numpy as np

src, report, out = sys.argv[1:4]
ids = sorted({sid for r in report.split(",") for sid in json.load(open(r))["sounds"]})
RATE = 22050
lines = ['// Generated by tools/scripts/mc_sound_export.py from Mario Combat. Do not edit.',
         '#include "mc_audio.h"', '']
table = []
for sid in ids:
    w = wave.open(os.path.join(src, f"{sid}.wav"), "rb")
    ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
    raw = w.readframes(n)
    a = np.frombuffer(raw, np.int16 if width == 2 else np.uint8).astype(np.float32)
    if width == 1:
        a = (a - 128) * 256
    a = a.reshape(-1, ch).mean(axis=1)
    if rate != RATE:
        t = np.arange(int(len(a) * RATE / rate)) * rate / RATE
        a = np.interp(t, np.arange(len(a)), a)
    pcm = np.clip(np.round(a), -32768, 32767).astype(np.int16)
    lines.append(f"static const int16 kSnd{sid}[] = {{{','.join(str(v) for v in pcm)}}};")
    table.append((sid, len(pcm)))
    print(sid, ch, width, rate, n, "->", len(pcm))
lines.append("const McSound kMcSounds[] = {")
for sid, n in table:
    lines.append(f"  {{{sid}, {n}, kSnd{sid}}},")
lines.append("};")
lines.append(f"const int kMcNumSounds = {len(table)};")
open(out, "w").write("\n".join(lines) + "\n")
