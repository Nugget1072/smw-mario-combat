"""Mario Combat's Bowser music (round 20) as a C array: generates src/mc/mc_music.c.
Usage: python -I mc_music_export.py <ffdec_sounds_dir> <out_c_file>
MC starts sound 560 on root frame 496 (Bowser's bridge): 194 s, 22050 Hz mono 16 bit (ADPCM in the SWF; FFDec's WAV
export of it is read here). Stored as 4-bit IMA ADPCM, one continuous stream from a predictor of 0 and step index 0,
two samples a byte (low nibble first); the game decodes it as it plays (mc_audio.c), looping.
"""
import os, sys, wave
import numpy as np

SOUND = 560
STEPS = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88, 97,
         107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658, 724, 796,
         876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428, 4871,
         5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623,
         27086, 29794, 32767]
INDEX = [-1, -1, -1, -1, 2, 4, 6, 8]


def encode(pcm):
    pred, idx, out = 0, 0, []
    for s in pcm:
        step = STEPS[idx]
        diff = int(s) - pred
        code = 0
        if diff < 0:
            code, diff = 8, -diff
        delta = step >> 3
        if diff >= step:
            code |= 4; diff -= step; delta += step
        step >>= 1
        if diff >= step:
            code |= 2; diff -= step; delta += step
        step >>= 1
        if diff >= step:
            code |= 1; delta += step
        pred = max(-32768, min(32767, pred - delta if code & 8 else pred + delta))
        idx = max(0, min(88, idx + INDEX[code & 7]))
        out.append(code)
    if len(out) & 1:
        out.append(0)
    return bytes(out[i] | out[i + 1] << 4 for i in range(0, len(out), 2))


def main():
    src, out_c = sys.argv[1:3]
    w = wave.open(os.path.join(src, '%d.wav' % SOUND), 'rb')
    ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
    a = np.frombuffer(w.readframes(n), np.int16 if width == 2 else np.uint8).astype(np.float32)
    if width == 1:
        a = (a - 128) * 256
    pcm = np.clip(a.reshape(-1, ch).mean(1), -32768, 32767).astype(np.int32)
    data = encode(pcm)
    L = ['// Mario Combat\'s Bowser music (sound %d): generated by tools/scripts/mc_music_export.py (do not edit).' % SOUND,
         '#include "mc_audio.h"', '', 'static const uint8 kBowserMusicAdpcm[%d] = {' % len(data)]
    for i in range(0, len(data), 32):
        L.append('  ' + ','.join(str(b) for b in data[i:i + 32]) + ',')
    L.append('};')
    L.append('const McMusic kMcBowserMusic = { %d, %d, kBowserMusicAdpcm };  // samples, Hz' % (len(pcm), rate))
    open(out_c, 'w', newline='\n').write('\n'.join(L) + '\n')
    print('sound %d: %d samples at %d Hz (%.1f s), %d bytes' % (SOUND, len(pcm), rate, len(pcm) / rate, len(data)))


if __name__ == '__main__':
    main()
