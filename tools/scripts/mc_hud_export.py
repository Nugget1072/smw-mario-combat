"""Export Mario Combat's life-bar HUD (DefineSprite 454) for the SMW port.

The HUD is stage-resolution art (1 px outlines, DefineText title), so FFDec renders it straight at the target
size (`-zoom 0.5 -format sprite:png -selectid 454 -export sprite`), keeping its antialiased text.
Red bar pixels (153,0,0) are flagged: in MC the bar is masked by `mask_mc._xscale = life / 10 * 100`.
Usage: python -I mc_hud_export.py <ffdec_render_1.png> <out_c_file> <preview.png>
"""
import sys
import numpy as np
from PIL import Image

src, out_c, prev = sys.argv[1:4]
o8 = np.asarray(Image.open(src).convert("RGBA"), np.uint8).copy()
H, W = o8.shape[:2]

# The "SUPER MARIO" title (rows 2-8 left of the bar) is MC's thin antialiased white text. At SNES size it is
# semi-transparent and washes out over light skies, so make it crisp: text pixels with alpha > 70 become opaque
# white, the rest of the label area clear, plus a 1 px outline in the bar's own red, darkened (readable on any
# background, like SMW's outlined status-bar text, and still MC's red/white HUD).
TEXT_ROWS, TEXT_COLS = slice(1, 10), slice(0, 77)
region = np.zeros((H, W), bool)
region[TEXT_ROWS, TEXT_COLS] = True
whitish = (o8[..., 0] > 150) & (o8[..., 1] > 150) & (o8[..., 2] > 150)
text = region & whitish & (o8[..., 3] > 70)
o8[region & ~text] = 0
o8[text] = (255, 255, 255, 255)
near = np.zeros((H, W), bool)
for dy in (-1, 0, 1):
    for dx in (-1, 0, 1):
        near |= np.roll(np.roll(text, dy, 0), dx, 1)
outline = near & ~text & region & (o8[..., 3] == 0)
o8[outline] = (80, 0, 0, 255)
is_bar = (np.abs(o8[..., 0].astype(int) - 153) <= 12) & (o8[..., 1] < 20) & (o8[..., 2] < 20) & (o8[..., 3] > 200)
bg = Image.new("RGBA", (W, H), (40, 60, 120, 255))
bg.alpha_composite(Image.fromarray(o8, "RGBA"))
bg.resize((W * 4, H * 4), Image.NEAREST).save(prev)
p = o8.astype(np.uint32)
packed = (p[..., 3] << 24) | (p[..., 0] << 16) | (p[..., 1] << 8) | p[..., 2]
cols = np.where(is_bar.any(axis=0))[0]
lines = ['// Generated by tools/scripts/mc_hud_export.py (Mario Combat life bar, DefineSprite 454). Do not edit.',
         '#include "mc_hud.h"', '',
         f"static const uint32 kHudPx[] = {{{','.join(f'0x{v:08x}' for v in packed.flatten())}}};",
         f"static const uint8 kHudBarPx[] = {{{','.join('1' if v else '0' for v in is_bar.flatten())}}};",
         f"const McHud kMcHud = {{{W}, {H}, {cols.min()}, {cols.max() + 1}, kHudPx, kHudBarPx}};"]
open(out_c, "w").write("\n".join(lines) + "\n")
print(W, H, "bar columns", cols.min(), cols.max())
