"""Export Mario Combat's own title logo (the fiery "Mario Combat" lettering of its main menu: shape 90, placed at
depth 2 of the root timeline from frame 306 and slid into place at the menuMenu label, frame 472) to C data for the
SMW title screen.

The shape is a bitmap fill on a black backdrop. It is rasterized at SCALE times the art scale (1 output pixel = 3 stage
pixels, as the hero's art). Mario Combat shows it as fire on black; over SMW's pale title background the thin letters
need that dark ground to stay readable, so the black stays as a soft smoky patch around the lettering (the lettering's
glow widened and blurred, at most BACK_ALPHA opaque) and fades out beyond it. Then it is cropped.
Usage: python -I mc_export_logo.py <MarioCombat.swf> <ffdec_images_dir> <out_c_file> <preview_png>
Writes the C file (`const McImage kMcTitleLogo`, ARGB straight alpha) and a preview, plus <out_c_file>.json (size,
crop, source).
"""
import json, os, sys
import numpy as np
from PIL import Image, ImageFilter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from swflib import Swf  # noqa: E402
from swfraster import raster_shape  # noqa: E402

LOGO_SHAPE = 90
STAGE_PER_ART = 3.0
SCALE = 1.25        # a little larger than the hero's art scale: about as wide as SMW's logo's MARIO WORLD line
BACK_ALPHA = 0.85   # the dark patch behind the lettering, at its densest
BACK_GROW = 3       # px the patch reaches beyond the lettering before it fades
BACK_LIT = 0.3      # how bright the glow must be to count as lettering for the patch (the faint fire is left out)
MIN_ALPHA = 12      # fainter pixels (of 255) are dropped


def main():
    swf_path, img_dir, out_c, preview = sys.argv[1:5]
    swf = Swf(swf_path)
    bitmaps = {}
    for f in os.listdir(img_dir):
        stem = f.split(".")[0]
        if stem.isdigit():
            bitmaps[int(stem)] = np.asarray(Image.open(os.path.join(img_dir, f)).convert("RGBA"), np.float32) / 255
    sh = swf.shapes[LOGO_SHAPE]
    k = SCALE / STAGE_PER_ART
    x0, x1, y0, y1 = [v / 20 for v in sh["bounds"]]
    w, h = int(np.ceil((x1 - x0) * k)), int(np.ceil((y1 - y0) * k))
    rgba = raster_shape(sh, bitmaps, (k / 20, 0, 0, k / 20, -x0 * k, -y0 * k), w, h)
    rgb = rgba[..., :3] * rgba[..., 3:4]           # the shape over its black backdrop
    glow = rgb.max(axis=2)                         # how much the lettering lights a pixel
    # the dark patch: where the lettering glows brightly, widened by BACK_GROW px, then softened
    lit = Image.fromarray((glow > BACK_LIT).astype(np.uint8) * 255, "L")
    patch = lit.filter(ImageFilter.MaxFilter(2 * BACK_GROW + 1)).filter(ImageFilter.GaussianBlur(BACK_GROW / 2))
    back = np.asarray(patch, np.float32) / 255 * BACK_ALPHA
    a = np.maximum(back, np.where(back > 0.02, glow, 0))  # (the faint fire beyond the patch is dropped)
    # colour over the patch: result = col * a + bg * (1 - a) = the lettering's light over a darkened background
    col = np.where(a[..., None] > 1e-4, rgb / np.maximum(a, 1e-4)[..., None], 0)
    a8 = np.clip(a * 255 + 0.5, 0, 255).astype(np.uint8)
    a8[a8 < MIN_ALPHA] = 0
    ys, xs = np.nonzero(a8)
    cy0, cy1, cx0, cx1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    a8 = a8[cy0:cy1, cx0:cx1]
    c8 = np.clip(col[cy0:cy1, cx0:cx1] * 255 + 0.5, 0, 255).astype(np.uint32)
    cw, ch = cx1 - cx0, cy1 - cy0
    argb = (a8.astype(np.uint32) << 24) | (c8[..., 0] << 16) | (c8[..., 1] << 8) | c8[..., 2]
    argb[a8 == 0] = 0
    Image.fromarray(np.dstack([c8.astype(np.uint8), a8]), "RGBA").save(preview)
    with open(out_c, "w", newline="\n") as f:
        f.write("// Generated by tools/scripts/mc_export_logo.py from MarioCombat.swf (shape %d): do not edit.\n"
                % LOGO_SHAPE)
        f.write('#include "mc_logo_data.h"\n\n')
        f.write("static const uint32 kPx[%d] = {\n" % (cw * ch))
        flat = argb.reshape(-1)
        for i in range(0, len(flat), 8):
            f.write("  " + ", ".join("0x%08x" % v for v in flat[i:i + 8]) + ",\n")
        f.write("};\n\n")
        f.write("const McImage kMcTitleLogo = { %d, %d, %.6ff, 0.0f, 0.0f, kPx };\n" % (cw, ch, k))
    json.dump({"shape": LOGO_SHAPE, "scale": k, "size": [int(cw), int(ch)], "crop_from": [int(cx0), int(cy0)],
               "raster_size": [w, h], "back_alpha": BACK_ALPHA, "back_grow": BACK_GROW, "back_lit": BACK_LIT,
               "min_alpha": MIN_ALPHA},
              open(out_c + ".json", "w"), indent=1)
    print("logo %dx%d (from %dx%d)" % (cw, ch, w, h))


if __name__ == "__main__":
    main()
